std::string libraryCommandName(std::string_view library, std::int32_t index)
{
    const std::string_view name = find(library, Kind::Command, index);
    return name.empty() ? placeholder(library, "命令", index) : std::string(name);
}

std::string libraryTypeName(std::string_view library, std::int32_t index)
{
    const std::string_view name = find(library, Kind::Type, index);
    return name.empty() ? placeholder(library, "类型", index) : std::string(name);
}

std::string libraryConstantName(std::string_view library, std::int32_t index)
{
    const std::string_view name = find(library, Kind::Constant, index);
    return name.empty() ? placeholder(library, "常量", index) : std::string(name);
}

std::string libraryMemberName(std::string_view library, std::int32_t type, std::int32_t index)
{
    const std::string_view name = find(library, Kind::Member, type, index);
    return name.empty() ? placeholder(library, "类型" + std::to_string(type) + "成员", index) : std::string(name);
}

