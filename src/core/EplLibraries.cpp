std::string_view find(std::string_view library, Kind kind, std::int32_t index, std::int32_t member = -1)
{
    const auto key = std::make_tuple(library, kind, index, member);
    const auto it = std::lower_bound(std::begin(kNames), std::end(kNames), key, [](const Name& n, const auto& k) {
        return std::make_tuple(n.library, n.kind, n.index, n.member) < k;
    });
    return it != std::end(kNames) && std::make_tuple(it->library, it->kind, it->index, it->member) == key
               ? it->name
               : std::string_view();
}

std::string placeholder(std::string_view library, std::string_view what, std::int32_t index)
{
    return "〈" + std::string(library) + std::string(what) + std::to_string(index) + "〉";
}

